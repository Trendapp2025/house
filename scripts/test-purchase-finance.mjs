import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync('src/lib/purchase-finance.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText;
const {calculatePurchase}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const property={price:180000,sellerType:'agency'};
const p={deposit:'40000',rate:'3.2',years:'30'};
const result=calculatePurchase(property,p);
assert.equal(result.principal,140000);
assert.ok(Math.abs(result.payment-605.45)<.02);
assert.equal(result.agency,5400);
assert.ok(Math.abs(result.liquidity-(40000+5400+180000*4000/170000))<.001);
assert.equal(calculatePurchase(property,{...p,rate:'0'}).payment,140000/360);
assert.equal(calculatePurchase(property,{...p,deposit:'180000'}).payment,0);
for(const deposit of ['-1','180001','Infinity',''])assert.equal(calculatePurchase(property,{...p,deposit}).valid,false);
for(const rate of ['-1','NaN',''])assert.equal(calculatePurchase(property,{...p,rate}).valid,false);
assert.equal(calculatePurchase({price:180000},p).agency,null);
assert.equal(calculatePurchase({price:180000,sellerType:'private'},p).agency,null);
assert.equal(calculatePurchase(property,p,[{label:'Coste documentato',amount:100,kind:'declared'}]).liquidity,result.liquidity+100);
assert.equal(calculatePurchase({price:219000},p).principal,179000);
console.log('PASS: ammortamento, tasso zero, acquisto senza mutuo, validazione, agenzia nota/sconosciuta, costi estensibili, preferenze su due prezzi.');
